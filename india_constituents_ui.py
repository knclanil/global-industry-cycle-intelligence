"""Compact, read-only NSE constituent explorer for Streamlit.

All data is generated by scripts/refresh_india_constituents.py in GitHub Actions
(or imported from user CSV files). No live NSE network access on page open.
No ranking / weights imputation / missing-membership penalties.
"""
from __future__ import annotations

from pathlib import Path
from html import escape
import pandas as pd
import streamlit as st

from india_constituents import FACTOR_FAMILIES, INDIA_INDICES

DATA = Path(__file__).resolve().parent / "data" / "india_holdings"


def _mtime(path: Path) -> int:
    return path.stat().st_mtime_ns if path.is_file() else 0


@st.cache_data(show_spinner=False, max_entries=12)
def _load_csv(path: str, modification_ns: int) -> pd.DataFrame:
    # modification_ns is intentionally part of the Streamlit cache key.
    if not Path(path).is_file():
        return pd.DataFrame()
    return pd.read_csv(path, dtype=str, keep_default_na=False)


def _get(filename: str) -> pd.DataFrame:
    path = DATA / filename
    return _load_csv(str(path), _mtime(path))



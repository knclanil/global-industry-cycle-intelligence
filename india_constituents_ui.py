def _source_context(status: pd.DataFrame) -> None:
    if status.empty:
        st.info("No NSE snapshots have been built yet. Run the India constituents refresh workflow; this page will display verified imported records when available.")
        return
    loaded = status[status["constituent_count"].astype(int) > 0]
    failures = status[status["status"].isin(["error", "cached_after_error"])]
    if loaded.empty:
        st.warning("None of the 31 index sources has a valid constituent snapshot yet. This is a source-collection issue, not an empty Indian equity market. Check **Data Coverage** below.")
    elif not failures.empty:
        st.caption(f"Using {len(loaded)} collected index snapshots. {len(failures)} source refreshes failed; earlier snapshots are reused where available. See Data Coverage for details.")
    else:
        st.caption(f"Using {len(loaded)} stored index snapshots. The app makes no NSE requests while rendering.")


def _render_company_directory(companies: pd.DataFrame, memberships: pd.DataFrame) -> None:
    st.markdown("#### Unified company directory")
    st.caption("One record per matched security/company identifier. All original source-index memberships remain available below.")
    c1, c2, c3 = st.columns([2.1, 1.2, 1.4])
    search = c1.text_input("Find company / NSE symbol / ISIN", placeholder="e.g., RELIANCE, TCS", key="in_co_search")
    family = c2.selectbox("Factor family", ["All factors"] + list(FACTOR_FAMILIES), key="in_co_family")
    membership_type = c3.selectbox("Index category", ["All categories", "Factor", "Sector", "Thematic", "Strategy"], key="in_co_type")
    available = companies.copy()
    if search:
        searched = search.strip().lower()
        mask = (available["company_name"].str.lower().str.contains(searched, regex=False)
                | available["symbol"].str.lower().str.contains(searched, regex=False)
                | available["isin"].str.lower().str.contains(searched, regex=False))
        available = available[mask]
    if family != "All factors":
        matching = set(memberships.loc[
            (memberships["category"] == "Factor") & (memberships["factor_family"] == family),
            "company_key"])
        available = available[available["company_key"].isin(matching)]
    if membership_type != "All categories":
        matching = set(memberships.loc[memberships["category"] == membership_type, "company_key"])
        available = available[available["company_key"].isin(matching)]
    view_cols = ["company_name", "symbol", "isin", "factor_families", "factor_universe_memberships",
                 "sector_indices", "thematic_indices", "strategy_indices", "index_count"]
    renamed = {"company_name": "Company", "symbol": "NSE Symbol", "isin": "ISIN",
               "factor_families": "Factor Families", "factor_universe_memberships": "Factor / Parent Universe",
               "sector_indices": "Sector Indices", "thematic_indices": "Thematic Indices",
               "strategy_indices": "Strategy Indices", "index_count": "Index Memberships"}
    st.caption(f"Showing {len(available):,} of {len(companies):,} consolidated records · Index memberships are counts, not rankings.")
    if available.empty:
        st.info("No companies match the filters.")
        return
    st.dataframe(available[view_cols].rename(columns=renamed), use_container_width=True,
                 hide_index=True, height=430)
    st.download_button("⬇ Export displayed companies", available.to_csv(index=False).encode("utf-8"),
                       file_name="india_company_constituent_directory.csv", mime="text/csv")
    st.markdown("#### Source-index detail")
    labels = {row["company_key"]: f'{row["company_name"]}  ·  {row["symbol"]}' for _, row in available.iterrows()}
    company_key = st.selectbox("Inspect a company", list(labels), format_func=lambda key: labels[key],
                               key="in_selected_company")
    selected = memberships[memberships["company_key"] == company_key].copy()
    identity = available.loc[available["company_key"] == company_key].iloc[0]
    st.markdown(f"<b>{escape(identity['company_name'])}</b> &nbsp; <span class='india-tag'>{escape(identity['symbol'])}</span>"
                f" <span class='india-tag'>{escape(identity['isin'] or 'ISIN not available')}</span>", unsafe_allow_html=True)
    display = selected[["index_name", "category", "factor_family", "parent_universe",
                        "weight_pct", "snapshot_utc", "source_type", "source_url"]].copy()
    display.columns = ["NSE Index", "Type", "Factor Family", "Parent Universe",
                       "Published Weight (%)", "Retrieved UTC", "Source Type", "Official CSV"]
    display["Published Weight (%)"] = display["Published Weight (%)"].replace("", "N/A")
    st.dataframe(display, hide_index=True, use_container_width=True, height=min(460, 95 + 35 * len(display)),
                 column_config={"Official CSV": st.column_config.LinkColumn("Official CSV", display_text="Open source")})
    if st.button("📊 Open India Company Financial KPI Intelligence", key="india_directory_open_financials", type="primary"):
        st.session_state.india_kpi_reference_symbol = str(identity['symbol']).upper()
        st.session_state.selected_page = 'India Company Financial KPI Intelligence'
        st.rerun()


def _render_factors(companies: pd.DataFrame, memberships: pd.DataFrame) -> None:
    st.markdown("#### Factor-family and parent-universe membership")
    st.caption("Factor families are consolidated, while every Nifty 50 / 100 / 200 / 500 source index remains a separate column. Parent universes are **not** pure large/mid/small-cap buckets.")
    factors = memberships[memberships["category"] == "Factor"].copy()
    if factors.empty:
        st.info("Factor CSVs have not been collected yet.")
        return
    left, right = st.columns([1.2, 1.5])
    families = sorted(factors["factor_family"].unique())
    current_family = left.selectbox("Explore factor family", ["All factor families"] + families, key="in_fam_select")
    universes = ["All parent universes"] + sorted(factors["parent_universe"].unique())
    current_universe = right.selectbox("Source parent universe", universes, key="in_universe_select")
    subset = factors
    if current_family != "All factor families":
        subset = subset[subset["factor_family"] == current_family]
    if current_universe != "All parent universes":
        subset = subset[subset["parent_universe"] == current_universe]
    if subset.empty:
        st.info("No imported memberships match that combination.")
        return
    base = companies[["company_key", "company_name", "symbol"]]
    pivot = subset.assign(present="✓").pivot_table(
        index="company_key", columns="index_name", values="present", aggfunc="first", fill_value="")
    pivot = pivot.reset_index()
    grid = base.merge(pivot, on="company_key", how="inner").drop(columns="company_key")
    grid = grid.rename(columns={"company_name": "Company", "symbol": "NSE Symbol"})
    st.caption(f"{len(grid):,} securities across {len(pivot.columns)-1} source indices · Blank = not listed in the selected snapshot; eligibility is not assessed.")
    st.dataframe(grid, use_container_width=True, hide_index=True, height=475)
    st.download_button("⬇ Export factor membership matrix", grid.to_csv(index=False).encode("utf-8"),
                       file_name="india_factor_membership_matrix.csv", mime="text/csv")
    st.markdown("#### Family coverage summary")
    family_data = (factors.groupby("factor_family")
                   .agg(distinct_companies=("company_key", "nunique"),
                        index_memberships=("index_slug", "size"),
                        source_indices=("index_slug", "nunique"))
                   .reset_index().rename(columns={"factor_family": "Factor Family",
                                                 "distinct_companies": "Unique Companies",
                                                 "index_memberships": "Index Memberships",
                                                 "source_indices": "Loaded Indices"}))
    st.dataframe(family_data.sort_values("Factor Family"), hide_index=True, use_container_width=True)
    st.markdown("#### Cross-universe factor overlap · exact memberships")
    st.caption("Exact intersection patterns across available Nifty parent universes. Membership overlap only; no eligibility penalties or ranking.")
    overlap_families = sorted(factors.groupby('factor_family')['index_slug'].nunique().loc[lambda x: x > 1].index)
    if overlap_families:
        overlap_family = st.selectbox('Factor to compare', overlap_families,
                                      index=overlap_families.index('Value') if 'Value' in overlap_families else 0,
                                      key='india_factor_overlap_selection')
        factor_set = factors[factors['factor_family'] == overlap_family].copy()
        presence = (factor_set.groupby('company_key')['index_name']
                    .agg(lambda names: tuple(sorted(set(names)))))
        company_names = dict(zip(companies['company_key'], companies['company_name']))
        symbols = dict(zip(companies['company_key'], companies['symbol']))
        exact = {}
        for key, pattern in presence.items():
            exact.setdefault(pattern, []).append(key)
        descriptions = []
        for pattern, member_keys in sorted(exact.items(), key=lambda v: (-len(v[1]), v[0])):
            descriptions.append({'Exact index combination': ' + '.join(pattern),
                                 'Unique companies': len(member_keys),
                                 'NSE symbols': ', '.join(sorted({symbols.get(k, '') for k in member_keys}))})
        exact_df = pd.DataFrame(descriptions)
        st.dataframe(exact_df, hide_index=True, use_container_width=True, height=min(430, 90 + 35 * len(exact_df)))
        st.download_button('⬇ Export factor overlap combinations', exact_df.to_csv(index=False).encode('utf-8'),
                           file_name=f'india_{overlap_family.lower().replace(" ", "_")}_exact_overlaps.csv', mime='text/csv',
                           key='india_factor_overlap_export')


def _render_sector_intersection(companies: pd.DataFrame, memberships: pd.DataFrame) -> None:
    st.markdown("#### Sector & thematic constituent explorer")
    sector = memberships[memberships["category"].isin(["Sector", "Thematic"])].copy()
    if sector.empty:
        st.info("Sector and thematic CSVs have not been collected yet.")
        return
    index_names = sorted(sector["index_name"].unique())
    selected_index = st.selectbox("Select sector or thematic index", index_names, key="in_sector_index")
    constituents = sector[sector["index_name"] == selected_index]
    merged = constituents[["company_key"]].merge(companies, on="company_key", how="left")
    display = merged[["company_name", "symbol", "isin", "factor_families",
                      "factor_universe_memberships", "sector_indices", "thematic_indices"]].copy()
    display.columns = ["Company", "NSE Symbol", "ISIN", "Factor Families", "Factor / Parent Universe",
                       "Sector Memberships", "Thematic Memberships"]
    st.caption(f"{len(constituents):,} constituents in **{selected_index}** (index membership, not portfolio weight).")
    st.dataframe(display, use_container_width=True, hide_index=True, height=370)
    st.markdown("#### Sector × factor intersections")
    st.caption("Number of constituent companies also appearing in each factor family. Counts are descriptive; overlapping sectors are not independent confirmations.")
    factors = memberships[memberships["category"] == "Factor"]
    sector_to_ids = sector.groupby("index_name")["company_key"].apply(set)
    family_to_ids = factors.groupby("factor_family")["company_key"].apply(set)
    rows = []
    for index_name, sector_keys in sector_to_ids.items():
        row = {"Sector / Theme": index_name, "Constituents": len(sector_keys)}
        for family in FACTOR_FAMILIES:
            row[family] = len(sector_keys & family_to_ids.get(family, set()))
        rows.append(row)
    matrix = pd.DataFrame(rows).sort_values("Sector / Theme")
    st.dataframe(matrix, hide_index=True, use_container_width=True, height=430)
    st.download_button("⬇ Export sector–factor intersections", matrix.to_csv(index=False).encode("utf-8"),
                       file_name="india_sector_factor_intersections.csv", mime="text/csv")


def _render_sources(status: pd.DataFrame, memberships: pd.DataFrame) -> None:
    st.markdown("#### NSE source-index browser")
    if status.empty:
        st.info("Source catalogue will populate after the first pipeline run.")
        return
    category = st.selectbox("Index category", ["All categories", "Sector", "Thematic", "Factor", "Strategy"],
                            key="in_source_category")
    subset = status if category == "All categories" else status[status["category"] == category]
    cols = ["index_name", "category", "factor_family", "parent_universe", "constituent_count",
            "status", "retrieved_utc", "source_type", "source_url"]
    display = subset[cols].copy()
    display.columns = ["NSE Index", "Category", "Factor", "Parent Universe", "Constituents",
                       "Refresh Status", "Retrieved UTC", "Data Origin", "Official CSV"]
    st.dataframe(display, hide_index=True, use_container_width=True, height=455,
                 column_config={"Official CSV": st.column_config.LinkColumn("Official CSV", display_text="NSE CSV")})
    indexed = status[status["constituent_count"].astype(int) > 0]
    if indexed.empty:
        return
